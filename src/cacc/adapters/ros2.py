"""ROS 2 parameter files for ``ros2_ws`` from a scenario and a controller.

    cacc ros2-params scenarios/ev_highway.yaml -c my_design.yaml -o case.yaml
    ros2 launch cacc_platoon platoon.launch.py params:=case.yaml

The distributed platoon (one node per car, a channel node for V2V) then runs
the same controller the offline engine tested: built-ins by name, plugins
and Controller Lab designs through the ``controller_options`` parameter
(a YAML string the vehicle node passes to ``make_controller``). This also
replaces keeping ``config/*.yaml`` in sync with ``scenarios/*.yaml`` by
hand.
"""

from __future__ import annotations

import yaml

LEADER_KEYS = ("profile", "t_start", "amplitude", "freq_hz", "duration", "decel",
               "value")


def params_from_scenario(tree: dict, controller: str = "cthp",
                         options: dict | None = None,
                         controller_block: dict | None = None) -> dict:
    """The ``/**: ros__parameters:`` mapping for a scenario mapping."""
    plat, veh = tree.get("platoon", {}), tree.get("vehicle", {})
    ctrl = {**tree.get("controller", {}), **(controller_block or {})}
    net, lead, sim = tree.get("network", {}), tree.get("leader", {}), tree.get("sim", {})
    p = {"sim_rate_hz": round(1.0 / float(sim.get("dt", 0.01)), 6),
         "beacon_rate_hz": float(net.get("msg_rate") or 25.0),
         "v0": float(plat.get("v0", 20.0)),
         "n_followers": int(plat.get("n_followers", 5)),
         "controller": controller,
         "controller_options": yaml.safe_dump(options or {}, default_flow_style=True,
                                              sort_keys=False).strip()}
    for k, d in (("tau", 0.1), ("length", 4.0), ("u_min", -8.0), ("u_max", 3.0)):
        p[k] = float(veh.get(k, d))
    for k, d in (("kp", 0.2), ("kd", 0.7), ("kv", 0.63), ("ka", 0.5), ("h", 0.7),
                 ("r", 2.5)):
        p[k] = float(ctrl.get(k, d))
    for k in LEADER_KEYS:
        if k in lead:
            p[k] = lead[k] if k == "profile" else float(lead[k])
    p["delay_s"] = float(net.get("delay", 0.0))
    p["loss_prob"] = float(net.get("loss_prob", 0.0))
    p["noise_rho"] = float(net.get("noise_rho") or 0.0)
    p["seed"] = int(sim.get("seed", 1))
    return {"/**": {"ros__parameters": p}}


def dump(params: dict, source: str = "") -> str:
    head = ("# ROS 2 parameters generated by `cacc ros2-params`"
            + (f" from {source}" if source else "") + "\n")
    return head + yaml.safe_dump(params, sort_keys=False)
