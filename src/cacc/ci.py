"""CI integration: PR comment, job summary and a status badge from a report.

Used by the GitHub Action (``action.yml``) after ``cacc stress`` or
``cacc evaluate``::

    cacc ci results/cacc/report.json --badge results/cacc/badge.svg \
        --summary "$GITHUB_STEP_SUMMARY" --comment

``--comment`` posts the result on the pull request that triggered the run
(GitHub REST API with ``$GITHUB_TOKEN``) and edits that same comment on
later pushes instead of piling up new ones. Nothing here needs a package
beyond the standard library.
"""

from __future__ import annotations

import json
import math
import os
import urllib.request
from pathlib import Path

MARKER = "<!-- cacc-ci-report -->"
MARK = {"PASS": "✅", "FAIL": "❌", "ERROR": "⚠️"}
COLOR = {"PASS": "#2ea043", "FAIL": "#cf222e", "ERROR": "#bf8700"}


def _fmt(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return "∞" if math.isinf(v) else f"{v:.3g}"
    return str(v)


def markdown(report: dict, title: str = "cacc controller gate") -> str:
    """The PR comment / job summary body for a plan or stress report."""
    c = report["counts"]
    head = (f"{MARKER}\n### {MARK.get(report['verdict'], '')} {title}: "
            f"**{report['verdict']}**\n\n"
            f"`{report.get('under_test', {}).get('controller', '')}` · {c['PASS']} pass · "
            f"{c['FAIL']} fail · {c['ERROR']} error · "
            f"{len(report.get('seeds', []))} seed(s)\n")
    camp = report.get("campaign")
    lines = [head]
    if camp:
        conds = camp["conditions"]
        lines.append("| maneuver \\ condition | "
                     + " | ".join(c["key"] for c in conds) + " |")
        lines.append("|---|" + "---|" * len(conds))
        for man, row in zip(camp["maneuvers"], camp["grid"], strict=True):
            cells = []
            for cell in row:
                if cell is None:
                    cells.append("")
                    continue
                cells.append(f"{MARK.get(cell['verdict'], '')} "
                             f"{cell['metric']} {_fmt(cell['worst'])}")
            lines.append(f"| {man['label']} | " + " | ".join(cells) + " |")
    else:
        lines.append("| case | verdict | tightest check |")
        lines.append("|---|---|---|")
        for case in report["cases"]:
            fails = [k for k in case.get("checks", []) if not k.get("passed", True)]
            k = (fails or case.get("checks") or [{}])[0]
            lines.append(f"| {case['name']} | {MARK.get(case['verdict'], '')} "
                         f"{case['verdict']} | {k.get('label', '')} "
                         f"(worst {_fmt(k.get('worst'))}) |")
    lines.append("\n<sub>Generated by cacc — rerun locally with the same plan "
                 "and seeds for the full report.</sub>")
    return "\n".join(lines) + "\n"


def badge_svg(report: dict, label: str = "cacc") -> str:
    """A flat shields-style SVG badge: ``cacc | PASS 21/21``."""
    c = report["counts"]
    total = sum(c.values())
    value = f"{report['verdict']} {c['PASS']}/{total}"
    lw, vw = 7 * len(label) + 12, 7 * len(value) + 12
    color = COLOR.get(report["verdict"], "#555")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{lw + vw}" height="20" '
            f'role="img" aria-label="{label}: {value}"><title>{label}: {value}</title>'
            f'<rect width="{lw}" height="20" fill="#555"/>'
            f'<rect x="{lw}" width="{vw}" height="20" fill="{color}"/>'
            '<g fill="#fff" text-anchor="middle" font-family="Verdana,DejaVu Sans,'
            'sans-serif" font-size="11">'
            f'<text x="{lw / 2}" y="14">{label}</text>'
            f'<text x="{lw + vw / 2}" y="14">{value}</text></g></svg>\n')


def pr_number(event_path: str | None = None) -> int | None:
    """The pull-request number of the triggering GitHub event, if any."""
    path = event_path or os.environ.get("GITHUB_EVENT_PATH")
    if not path or not Path(path).is_file():
        return None
    event = json.loads(Path(path).read_text(encoding="utf-8"))
    pr = event.get("pull_request") or event.get("issue", {})
    return pr.get("number")


def _api(method: str, url: str, token: str, body: dict | None = None,
         opener=urllib.request.urlopen):
    req = urllib.request.Request(
        url, method=method, data=None if body is None else json.dumps(body).encode(),
        headers={"Authorization": f"Bearer {token}",
                 "Accept": "application/vnd.github+json",
                 "Content-Type": "application/json"})
    with opener(req) as resp:
        return json.loads(resp.read() or b"null")


def post_comment(body: str, repo: str, number: int, token: str,
                 api: str = "https://api.github.com",
                 opener=urllib.request.urlopen) -> str:
    """Create or update this tool's comment on PR ``number``; 'created' /
    'updated'."""
    base = f"{api}/repos/{repo}/issues/{number}/comments"
    old = [c for c in _api("GET", base + "?per_page=100", token, opener=opener)
           if MARKER in (c.get("body") or "")]
    if old:
        _api("PATCH", f"{api}/repos/{repo}/issues/comments/{old[0]['id']}", token,
             {"body": body}, opener)
        return "updated"
    _api("POST", base, token, {"body": body}, opener)
    return "created"


def run(report_path: str, badge: str | None = None, summary: str | None = None,
        comment: bool = False, title: str = "cacc controller gate") -> list[str]:
    """What ``cacc ci`` does; returns one line per action taken."""
    report = json.loads(Path(report_path).read_text(encoding="utf-8"))
    body = markdown(report, title)
    done = []
    if badge:
        Path(badge).parent.mkdir(parents=True, exist_ok=True)
        Path(badge).write_text(badge_svg(report), encoding="utf-8")
        done.append(f"badge: {badge}")
    if summary:
        with open(summary, "a", encoding="utf-8") as f:
            f.write(body)
        done.append(f"summary: {summary}")
    if comment:
        num, repo = pr_number(), os.environ.get("GITHUB_REPOSITORY")
        token = os.environ.get("GITHUB_TOKEN")
        if not (num and repo and token):
            done.append("comment: skipped (not a pull request, or no GITHUB_TOKEN)")
        else:
            how = post_comment(body, repo, num, token,
                               os.environ.get("GITHUB_API_URL", "https://api.github.com"))
            done.append(f"comment: {how} on #{num}")
    if not done:
        print(body)
    return done
