"""Model-adequacy checks for drive-log twins (fix of 2026-10-08).

A twin fitted to data generated by its own model family recovers its
parameters with tiny error bars; that proves the optimiser, not the model.
On a real car the error is dominated by *structural* mismatch, which the
Jacobian standard errors cannot see. These checks make that visible:

* **Structure comparison.** Every hop is fitted with the classic lag model
  (``a' = (u - a)/tau``) and with a lag + actuation dead-time model, the
  structure published field studies use (Gunter et al., IEEE T-ITS). The
  structures are compared with a BIC whose sample size is the effective one
  (residuals of a time series are autocorrelated):
  ``BIC = m_eff ln(MSE) + p ln(m_eff)``, ``m_eff = m (1 - rho1) / (1 + rho1)``.
  When the two are within ``BIC_COMPARABLE`` the data cannot tell them apart,
  and the audit plans for the more conservative one.
* **Fit quality.** The share of measured gap and speed variation the twin
  explains (R^2), and the lag-1 autocorrelation of the residuals: near 1
  means the model misses systematic behaviour.

:func:`assess` folds these into ``confidence`` = ``high`` / ``medium`` /
``low`` plus plain-language warnings, shown next to every verdict.
"""

from __future__ import annotations

import math

import numpy as np

#: |delta BIC| below which two structures count as equally supported
BIC_COMPARABLE = 10.0
#: minimum share of gap / speed variation the twin must explain
R2_MIN = 0.8
#: residual lag-1 autocorrelation above which mismatch is flagged
RHO_MAX = 0.95
#: disagreement in the minimum stable time gap that lowers confidence [s]
T_MIN_SPREAD = 0.3


def effective_n(m: int, rho1: float) -> float:
    """Effective sample size of ``m`` AR(1)-correlated residuals."""
    rho1 = float(np.clip(rho1, 0.0, 0.99))
    return max(m * (1.0 - rho1) / (1.0 + rho1), 10.0)


def bic(cost: float, m: int, n_par: int, rho1: float) -> float:
    """BIC with the effective sample size; ``cost`` = 0.5 * sum(r^2)."""
    m_eff = effective_n(m, rho1)
    mse = max(2.0 * cost / max(m, 1), 1e-300)
    return m_eff * math.log(mse) + n_par * math.log(m_eff)


def r_squared(err: np.ndarray, ref: np.ndarray) -> float:
    """Share of the variance of ``ref`` explained (1 - MSE / var)."""
    var = float(np.var(ref))
    if var <= 0.0:
        return float("nan")
    return 1.0 - float(np.mean(np.asarray(err) ** 2)) / var


def assess(r2_gap: float, r2_speed: float, rho1: float, verdict: str,
           t_min: float | None, alt: dict | None) -> tuple[str, list[str]]:
    """Confidence level and warnings for one twin.

    ``alt`` is the alternative structure's summary (``verdict``,
    ``min_string_stable_time_gap_s``, ``comparable``) or None.
    """
    level, warns = 2, []
    worst = min(r2_gap, r2_speed)
    if not math.isfinite(worst) or worst < R2_MIN:
        level = 0
        warns.append(f"the twin explains only {100 * max(worst, 0.0):.0f}% of "
                     "the measured gap/speed variation")
    if rho1 > RHO_MAX:
        level = min(level, 1)
        warns.append(f"residuals are strongly autocorrelated (lag-1 "
                     f"{rho1:.2f}): the model misses systematic behaviour, so "
                     "the error bars are optimistic")
    if alt is not None and alt.get("comparable"):
        a_verdict = alt.get("verdict")
        a_tmin = alt.get("min_string_stable_time_gap_s")
        if {verdict, a_verdict} == {"string-stable", "string-unstable"}:
            level = 0
            warns.append("the lag and lag+delay model structures fit about "
                         "equally well but give opposite verdicts")
        elif (t_min is None) != (a_tmin is None):
            level = 0
            warns.append("one plausible model structure is unstable at every "
                         "time gap; the other is not")
        elif (t_min is not None and a_tmin is not None
              and abs(t_min - a_tmin) > T_MIN_SPREAD):
            level = min(level, 1)
            warns.append("plausible model structures disagree on the minimum "
                         f"stable time gap by {abs(t_min - a_tmin):.2f} s")
    return ("low", "medium", "high")[level], warns
