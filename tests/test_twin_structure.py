"""Twin structure selection and confidence (fix of 2026-10-08).

The original twin was validated only on data generated by its own lag
model, so its tiny error bars proved the optimiser rather than the model.
These tests pin the new safeguards: a lag + dead-time structure that wins
only on strong evidence, a recommendation that survives every plausible
structure, and a confidence level that drops when the fit is poor.
"""

import numpy as np
import pytest

from cacc.twin import LinearACC, calibrate_log, synthesize_log
from cacc.twin_checks import assess, bic, effective_n

T10 = np.round(np.arange(0.0, 200.0, 0.1), 2)


def perturbed_leader(t):
    v = np.full_like(t, 25.0)
    for t0, dur, dv in ((20, 10, -4.0), (80, 12, 3.0), (140, 8, -5.0)):
        up = np.clip((t - t0) / dur, 0, 1)
        dn = np.clip((t - t0 - dur - 15) / dur, 0, 1)
        v += dv * (0.5 - 0.5 * np.cos(np.pi * up)) - dv * (0.5 - 0.5 * np.cos(np.pi * dn))
    return v


LAGGED = LinearACC(k_s=0.10, k_v=0.30, T=1.4, s0=4.0, tau=0.8)
DEAD_TIME = LinearACC(k_s=0.10, k_v=0.30, T=1.6, s0=4.0, tau=0.3, delay=0.4)


@pytest.fixture(scope="module")
def lag_report():
    log = synthesize_log([LAGGED], T10, perturbed_leader(T10), ["Lead", "Car"],
                         seed=3)
    return calibrate_log(log)[0][0]


@pytest.fixture(scope="module")
def delay_report():
    log = synthesize_log([DEAD_TIME], T10, perturbed_leader(T10), ["Lead", "Car"],
                         seed=5)
    return calibrate_log(log)[0][0]


def test_lag_data_keeps_the_lag_twin_with_high_confidence(lag_report):
    r = lag_report
    assert r.structure == "lag"
    assert r.confidence == "high" and not r.warnings
    assert r.model.tau == pytest.approx(0.8, rel=0.03)
    alt = r.alternative
    assert alt["structure"] == "lag+delay" and alt["comparable"]
    assert alt["verdict"] == r.verdict  # plausible structures agree


def test_dead_time_is_recovered_when_it_is_there(delay_report):
    r = delay_report
    assert r.structure == "lag+delay"
    assert not r.alternative["comparable"]  # the lag twin is clearly worse
    # with this excitation only the total effective lag is well identified
    # (the lag / dead-time split varies with the noise seed); the verdict
    # and the minimum stable time gap do not depend on the split
    assert r.model.tau + r.model.delay == pytest.approx(0.7, abs=0.05)
    assert r.model.delay > 0.2
    assert r.min_time_gap == pytest.approx(DEAD_TIME.min_stable_time_gap(), abs=0.05)
    assert r.to_dict()["structure"] == "lag+delay"


def test_an_unidentified_split_is_reported(delay_report):
    r = delay_report
    if r.model.tau <= 0.0505 or r.model.delay < 1e-3:
        assert any("not separately identified" in w for w in r.warnings)
    else:
        assert not any("not separately identified" in w for w in r.warnings)


def test_twin_scenario_carries_the_dead_time(delay_report):
    vehicle = delay_report.model.scenario(25.0)["vehicle"]
    assert vehicle["act_delay"] == pytest.approx(delay_report.model.delay, abs=1e-3)
    assert "act_delay" not in LAGGED.scenario(25.0)["vehicle"]


def test_noisy_data_lowers_confidence():
    log = synthesize_log([LAGGED], T10, perturbed_leader(T10), ["Lead", "Car"],
                         seed=3, speed_noise=0.6, gap_noise=2.0)
    r = calibrate_log(log)[0][0]
    assert r.confidence == "low"
    assert any("explains only" in w for w in r.warnings)


def test_assess_rules():
    ok = {"comparable": True, "verdict": "string-stable",
          "min_string_stable_time_gap_s": 1.5}
    assert assess(0.99, 0.99, 0.1, "string-stable", 1.5, ok) == ("high", [])
    level, w = assess(0.99, 0.99, 0.1, "string-unstable", 1.5, ok)
    assert level == "low" and "opposite verdicts" in w[0]
    level, w = assess(0.99, 0.99, 0.1, "string-stable", 1.9, ok)
    assert level == "medium" and "disagree" in w[0]
    level, _ = assess(0.99, 0.99, 0.97, "string-stable", 1.5, None)
    assert level == "medium"  # strongly autocorrelated residuals
    level, _ = assess(0.5, 0.99, 0.1, "string-stable", 1.5, None)
    assert level == "low"
    # a clearly worse alternative is ignored
    far = dict(ok, comparable=False, verdict="string-unstable")
    assert assess(0.99, 0.99, 0.1, "string-stable", 1.5, far)[0] == "high"


def test_bic_uses_the_effective_sample_size():
    assert effective_n(1000, 0.0) == pytest.approx(1000)
    assert effective_n(1000, 0.9) == pytest.approx(1000 * 0.1 / 1.9)
    # one more parameter for the same fit costs ln(m_eff)
    m_eff = effective_n(1000, 0.0)
    assert bic(1.0, 1000, 6, 0.0) - bic(1.0, 1000, 5, 0.0) == pytest.approx(
        np.log(m_eff))
